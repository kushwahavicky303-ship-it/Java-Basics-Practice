package variables;

public class typesconversion {
    public static void main(String[] args){
        System.out.println("welcome to typeconversion program:");
        //implicit conversion
        //(byte to int)
        byte b = 24;
        int i ;
        i = b;
        System.out.println(i);//24
        //character to int
        int num = 1000;
        double value = num;
        System.out.println(value);


    }
}
