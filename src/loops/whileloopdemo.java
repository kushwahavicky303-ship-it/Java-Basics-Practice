package loops;

public class whileloopdemo {
    public static void main(String[] args){
        System.out.println("welcome to while loops:");
        int i = 1;
        while(i <= 10){
            System.out.println(i);
            i++;
        }
        //for reversing...
        int j = 10;
        while(j >= 1){//while(j++ <=1)then no need of updation.....
            System.out.println(j);
            j--;
        }

    }
}
