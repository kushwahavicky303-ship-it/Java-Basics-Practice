package operators;

public class incrementdecrement {
    public static void main(String[] args){
        System.out.println("welcome to increasement and decrement operattors:");
        int i = 5;
        i++;//i=i+1
        System.out.println(i);
        //decrement
        int a = 5;
        a--;//a = a-1-->a-=1;
        System.out.println(a);
    }
}
